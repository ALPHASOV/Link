#include "IO.h"

/****************************************************************************
// 过程:	void IO_vInit(void) 
//
//----------------------------------------------------------------------------
// 描述:	初始化I/O口：.
//
//----------------------------------------------------------------------------
// 返回值:	无.
//
//----------------------------------------------------------------------------
// 参数:	无.
//
****************************************************************************/

void IO_vInit(void)
{
	
	//初始化IO输出值

	CLEARIO_P1_0;	//控制开关SW1、SW2、预上电、SW3、SW4、SW5、SW6，
	CLEARIO_P1_1;
	CLEARIO_P1_2;
	CLEARIO_P1_3;
	CLEARIO_P1_4;
	CLEARIO_P1_5;
	CLEARIO_P1_6;
	CLEARIO_P1_7;	//备用，可用于调试

	CLEARIO_P2_12;	//P2.12用于控制指示灯

	CLEARIO_P0_0;	//输出数据
	CLEARIO_P0_1;	//读入数据
	CLEARIO_P0_2;	//读写时钟
	CLEARIO_P0_3;	//铁电片选

  ///  -----------------------------------------------------------------------
  ///  设置 P0:
  ///  -----------------------------------------------------------------------
  ///  P0.0：	输出，高低电平 
  ///  P0.1 ：	输入，高低电平
  ///  P0.2：	输出，上升沿有效
  ///  P0.3：	输出，低电平有效
  ///  P0.4~7:	输入，高低电平

  P0_IOCR00 = 0x0080;      // 输出，高低电平
  P0_IOCR01 = 0x0010;      // 输入，高低电平
  P0_IOCR02 = 0x0080;      // 输出，高低电平
  P0_IOCR03 = 0x0080;      // 输出，高低电平
  P0_IOCR04 = 0x0010;      // 输入，高低电平
  P0_IOCR05 = 0x0010;      // 输入，高低电平
  P0_IOCR06 = 0x0010;      // 输入，高低电平
  P0_IOCR07 = 0x0010;      // 输入，高低电平

  ///  -----------------------------------------------------------------------
  ///  设置 P1:
  ///  -----------------------------------------------------------------------
  ///  P1.0~6 ：输出，高低电平

  P1_IOCR00      =  0x0080;      // 输出，高低电平
  P1_IOCR01      =  0x0080;      // 输出，高低电平
  P1_IOCR02      =  0x0080;      // 输出，高低电平
  P1_IOCR03      =  0x0080;      // 输出，高低电平
  P1_IOCR04      =  0x0080;      // 输出，高低电平
  P1_IOCR05      =  0x0080;      // 输出，高低电平
  P1_IOCR06      =  0x0080;      // 输出，高低电平
  P1_IOCR07      =  0x0080;      // 备用，输出，高低电平

  ///  -----------------------------------------------------------------------
  ///  设置 P2:
  ///  -----------------------------------------------------------------------
  ///  P2.12 ：输出，高低电平

  P2_IOCR12      =  0x0080;       // 输出，高低电平
  
  ///  -----------------------------------------------------------------------
  ///  设置 P10:
  ///  -----------------------------------------------------------------------
  ///  P10.4~9 ：输入，高低电平

  P10_IOCR04      =  0x0010;      // 输入，高低电平
  P10_IOCR05      =  0x0010;      // 输入，高低电平
  P10_IOCR06      =  0x0010;      // 输入，高低电平
  P10_IOCR07      =  0x0010;      // 输入，高低电平
  P10_IOCR08      =  0x0010;      // 输入，高低电平
  P10_IOCR09      =  0x0010;      // 输入，高低电平

} //  End of function IO_vInit

